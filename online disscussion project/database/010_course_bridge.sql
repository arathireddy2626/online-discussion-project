-- Step 10: bridge the professor's rubric schema with the Course class of the class design.
--
-- The rubric schema (005) has no Course table: discussions carry a free-text CourseName
-- column and enrolment is tracked through the EnrollQueue / RemoveStudentQueue request
-- queues. The class design requires a Course that owns
--   * courseName, courseNumber
--   * a collection of Student
--   * a collection of Discussion
--
-- This migration adds the missing tables without renaming or dropping any of the rubric
-- tables, so the existing Node.js server and the professor's ER diagram stay valid.
--
-- Run once, after 009_archive_files.sql.

USE discussion_tool;

-- ---------------------------------------------------------------------------
-- Course table (rubric spelling: lowercase table names).
-- course_number is the natural key used by the Java Course class.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS course (
    course_number VARCHAR(30) NOT NULL,
    course_name VARCHAR(200) NOT NULL,
    instructor_username VARCHAR(60) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (course_number),
    KEY idx_course_instructor (instructor_username),
    CONSTRAINT fk_course_instructor
        FOREIGN KEY (instructor_username) REFERENCES LoginCredential (Username)
        ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- Enrolled students of a course. Replaces the ad-hoc "is this student enrolled?"
-- logic with an explicit relationship table.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS course_student (
    course_number VARCHAR(30) NOT NULL,
    student_id INT NOT NULL,
    enrolled_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (course_number, student_id),
    KEY idx_course_student_student (student_id),
    CONSTRAINT fk_course_student_course
        FOREIGN KEY (course_number) REFERENCES course (course_number)
        ON DELETE CASCADE,
    CONSTRAINT fk_course_student_student
        FOREIGN KEY (student_id) REFERENCES StudentRecord (StudentID)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- Link each discussion to the course that owns it.
-- The rubric stores the course as free text in Dicussion.CourseName; CourseNumber is the
-- formal foreign key. Both are kept in sync by the Java DBInterface.
-- ---------------------------------------------------------------------------
ALTER TABLE Dicussion
    ADD COLUMN CourseNumber VARCHAR(30) NULL AFTER DiscussionID;

ALTER TABLE Dicussion
    ADD CONSTRAINT fk_discussion_course
        FOREIGN KEY (CourseNumber) REFERENCES course (course_number)
        ON DELETE SET NULL;

CREATE INDEX idx_discussion_course ON Dicussion (CourseNumber);

-- ---------------------------------------------------------------------------
-- Seed the course that the existing data belongs to. The instructor account
-- 'drKasi' is assumed to exist by the time of installation.
-- ---------------------------------------------------------------------------
INSERT INTO course (course_number, course_name, instructor_username)
VALUES ('SWE-101', 'Software Engineering', 'drKasi')
ON DUPLICATE KEY UPDATE course_name = VALUES(course_name);

-- Point the existing discussions at that course.
UPDATE Dicussion
SET CourseNumber = 'SWE-101'
WHERE CourseNumber IS NULL;

-- Enrol the students that already hold a login credential. The instructor is the
-- course owner and is therefore not enrolled as a student.
INSERT IGNORE INTO course_student (course_number, student_id)
SELECT 'SWE-101', s.StudentID
FROM StudentRecord s
WHERE s.Username IS NOT NULL;

